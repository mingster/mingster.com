#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# riben.life -> mingster.com sync manifest
#
# Model: riben.life is upstream. EVERYTHING syncs by default.
# mingster.com owns only three feature areas plus its identity/config files.
# Those are listed in PROTECT and are never overwritten.
#
# Pattern syntax is rsync filter syntax, anchored at the repo root:
#   /web/src/lib/auth.ts     -> exactly that file
#   /web/src/app/blog/***    -> that directory and everything under it
#
# rsync protects excluded paths from --delete, so a single list covers both
# "don't copy over it" and "don't prune it".
# ---------------------------------------------------------------------------

RIBEN_REPO="${RIBEN_REPO:-$HOME/projects/riben.life}"
RIBEN_BRANCH="${RIBEN_BRANCH:-main}"

# ===========================================================================
# PROTECT — mingster.com owns these. Upstream changes here are REPORTED,
# never applied. If you want an upstream change to a protected file, port it
# by hand.
# ===========================================================================
PROTECT=(
  # --- Auth (mingster has its own Better Auth config, own providers) -------
  '/web/src/lib/auth.ts'
  '/web/src/lib/auth-client.ts'
  '/web/src/lib/auth-utils.ts'
  '/web/src/components/auth/***'
  '/web/src/app/auth/***'
  '/web/src/app/api/auth/***'
  '/web/src/app/(root)/signIn/***'
  '/web/src/providers/session-provider.tsx'
  '/web/src/lib/recaptcha-verify.ts'
  '/web/src/utils/isAdmin.ts'

  # --- Blog (mingster-only content + renderer) ----------------------------
  '/web/blogData/***'
  '/web/src/app/blog/***'
  '/web/src/mdx-components.tsx'
  '/web/public/img/beams/***'

  # --- Virtual experience / avatar / chat ---------------------------------
  '/web/src/app/page.tsx'                       # home page renders VirtualExperienceClient
  '/web/src/components/virtual-experience/***'
  '/web/src/types/virtual-experience.ts'
  '/web/src/app/api/chat/***'
  '/web/src/hooks/useChat.tsx'
  '/web/public/models/***'
  '/web/public/animations/***'
  '/web/scripts/patch-three-clock.js'
  '/web/bin/compress-character-glb.ts'

  # --- Platform subscription (mingster-only; riben has no equivalent) -----
  # Remove these entries if you ever want riben's payment/* to take over.
  '/web/src/app/subscribe/***'
  '/web/src/app/account/subscription/***'
  '/web/src/app/api/subscribe/***'
  '/web/src/lib/stripe/***'                     # legacy path, imported by auth.ts
  '/web/src/lib/credit-bonus.ts'

  # --- Site identity, branding, static pages ------------------------------
  '/web/src/app/(root)/about/***'
  '/web/src/app/(root)/privacy/***'
  '/web/src/app/(root)/terms/***'
  '/web/public/favicons/***'
  '/web/src/components/site-footer.tsx'
  '/web/src/app/robots.ts'
  '/web/src/app/sitemap.ts'

  # --- Build / deploy / tooling config ------------------------------------
  '/web/package.json'          # deps reported by dep-drift.mjs, never overwritten
  '/web/bun.lock'
  '/web/next.config.ts'
  '/web/vercel.json'
  '/web/tsconfig.json'
  '/web/biome.json'
  '/web/next-env.d.ts'
  '/web/bin/deploy.sh'
  '/web/bin/probe-server.sh'
  '/web/.env'
  '/web/.env.*'

  # --- Repo metadata ------------------------------------------------------
  '/AGENTS.md'
  '/CLAUDE.md'
  '/README.md'
  '/SECURITY.md'
  '/LICENSE'
  '/.gitignore'
  '/.gitattributes'
  '/.claude/***'
  '/.cursor/***'
  '/.agents/***'
  '/.vscode/***'
  '/doc/***'
  '/bin/sync/***'              # this tooling
  '/*.code-workspace'
  '/.riben-sync-state'
)

# ===========================================================================
# EXCLUDE — riben-specific, never wanted in mingster.
# ===========================================================================
EXCLUDE=(
  '/.git/***'
  '/.DS_Store'
  '.DS_Store'
  '/fileServer/***'            # riben's Obsidian doc vault
  '/docs/***'                  # riben doc tree (mingster uses /doc)
  '/asset/***'                 # riben product pattern art
  '/CHANGELOG.md'
  '/riben-life.code-workspace'
  '/web/prisma/migrations/***'  # mingster uses `prisma db push`, no migration history
  '/web/prisma/generated/***'   # generated by `bun run sql:generate`
  '/web/node_modules/***'
  '/web/.next/***'
  '/web/test-results/***'
  '/web/playwright-report/***'
  '/web/e2e/***'
  # riben's root /bin holds its own deploy/pm2/pg_backup/cron scripts with
  # hardcoded riben hosts and paths. mingster deploys via web/bin/deploy.sh.
  # If you want one of riben's cron runners, copy it over by hand and fix paths.
  '/bin/***'
)

# ===========================================================================
# MERGE — synced with a custom merger instead of a plain file copy.
# i18n translation files: riben is the base, mingster-only keys are re-added
# (mingster has ~470 en/tw keys riben does not).
# ===========================================================================
I18N_MERGE_GLOB='web/src/app/i18n/locales/*/*.json'

# ===========================================================================
# REVIEW — synced, but always called out in the report because a copy alone
# is not enough to keep the app working.
# ===========================================================================
REVIEW=(
  'web/prisma/schema.prisma'   # needs `bun run sql:generate` + `bun run dbpush`
  'web/src/proxy.ts'
  'web/src/app/layout.tsx'
  'web/src/app/css/globals.css'
  'web/bin/install.ts'
  'web/public/install/'
)
